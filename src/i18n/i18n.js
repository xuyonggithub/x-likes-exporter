  var current = 'en';
  if (typeof navigator !== 'undefined') current = detect();

  function normalize(lang) {
    var l = String(lang || '').toLowerCase().replace(/_/g, '-');
    if (l === 'zht' || l === 'zh-hant') return 'zht';
    // 中文要区分简繁：zh-Hant / zh-TW / zh-HK / zh-MO → zht，其余（zh、zh-CN、zh-Hans…）→ zh
    if (l.split('-')[0] === 'zh') {
      return /(hant|tw|hk|mo)/.test(l) ? 'zht' : 'zh';
    }
    var base = l.split('-')[0];
    return LANGS.indexOf(base) >= 0 ? base : null;
  }

  function detect() {
    var list = [];
    if (typeof navigator !== 'undefined') {
      list = (navigator.languages && navigator.languages.length)
        ? navigator.languages
        : [navigator.language || ''];
    }
    for (var i = 0; i < list.length; i++) {
      var n = normalize(list[i]);
      if (n) return n;
    }
    return 'en';
  }

  function setLocale(code) {
    var n = normalize(code);
    current = n || detect();
    return current;
  }

  function getLocale() {
    return current;
  }

  function t(key, params) {
    var table = DICT[current] || DICT.en;
    var s = table[key];
    if (s == null) s = DICT.en[key] != null ? DICT.en[key] : key;
    if (params) {
      Object.keys(params).forEach(function (k) {
        s = s.split('{' + k + '}').join(params[k]);
      });
    }
    return s;
  }

